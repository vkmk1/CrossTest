"""CRSP daily pull from WRDS (DATA.md §2).

Universe: CRSP common shares (shrcd in {10, 11}) on NYSE/AMEX/NASDAQ (exchcd in {1, 2, 3}).
Fields: permno, date, prc, ret, vol, shrout, openprc, askhi, bidlo.

Credentials come from ``~/.pgpass`` via the ``wrds`` package; nothing is hard-coded.
The pull is chunked by calendar month and written one Parquet file per year to
``<data_root>/raw/crsp_daily/{year}.parquet``. No cleaning happens here; see ``bars.py``.

Two sources are supported:

- ``siz`` (default, per DATA.md): legacy ``crsp.dsf`` joined to ``crsp.dsenames``.
- ``ciz``: the CRSP CIZ (v2) format, ``crsp.dsf_v2`` joined to ``crsp.stocknames_v2``, renamed
  to the legacy column names. WRDS froze the legacy SIZ files at the 2024 year-end
  update, so 2025 may only exist in CIZ. Check the schema on a one-month pull before using it.

Usage::

    python -m mstate.data.wrds_pull --start 2010-01-01 --end 2010-01-31 --dry-run
    python -m mstate.data.wrds_pull --start 2010-01-01 --end 2010-01-31 --tag month_check
    python -m mstate.data.wrds_pull --start 2010-01-01 --end 2025-12-31
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path
from typing import Any

import pandas as pd

from mstate.utils.paths import raw_dir

COLUMNS = ["permno", "date", "prc", "ret", "vol", "shrout", "openprc", "askhi", "bidlo"]

SIZ_SQL = """
SELECT a.permno, a.date, a.prc, a.ret, a.vol, a.shrout, a.openprc, a.askhi, a.bidlo
FROM crsp.dsf AS a
JOIN crsp.dsenames AS b
  ON a.permno = b.permno
 AND a.date BETWEEN b.namedt AND COALESCE(b.nameendt, DATE '9999-12-31')
WHERE a.date BETWEEN DATE '{start}' AND DATE '{end}'
  AND b.shrcd IN (10, 11)
  AND b.exchcd IN (1, 2, 3)
"""

# CIZ: share-code 10/11 is approximately sharetype NS + securitytype EQTY + securitysubtype COM
# + US-incorporated; exchcd 1/2/3 is primaryexch N/A/Q. Verify on a one-month pull.
CIZ_SQL = """
SELECT a.permno, a.dlycaldt AS date, a.dlyprc AS prc, a.dlyret AS ret, a.dlyvol AS vol,
       a.shrout, a.dlyopen AS openprc, a.dlyhigh AS askhi, a.dlylow AS bidlo
FROM crsp.dsf_v2 AS a
JOIN crsp.stocknames_v2 AS b
  ON a.permno = b.permno
 AND a.dlycaldt BETWEEN b.namedt AND COALESCE(b.nameenddt, DATE '9999-12-31')
WHERE a.dlycaldt BETWEEN DATE '{start}' AND DATE '{end}'
  AND b.sharetype = 'NS'
  AND b.securitytype = 'EQTY'
  AND b.securitysubtype = 'COM'
  AND b.usincflg = 'Y'
  AND b.issuertype IN ('ACOR', 'CORP')
  AND b.primaryexch IN ('N', 'A', 'Q')
"""

SQL = {"siz": SIZ_SQL, "ciz": CIZ_SQL}


def month_chunks(start: str, end: str) -> list[tuple[str, str]]:
    s, e = pd.Timestamp(start), pd.Timestamp(end)
    out = []
    cur = s
    while cur <= e:
        nxt = min(cur + pd.offsets.MonthEnd(0), e)
        out.append((cur.strftime("%Y-%m-%d"), nxt.strftime("%Y-%m-%d")))
        cur = nxt + pd.Timedelta(days=1)
    return out


def _coerce(df: pd.DataFrame) -> pd.DataFrame:
    df = df[COLUMNS].copy()
    df["permno"] = df["permno"].astype("int64")
    df["date"] = pd.to_datetime(df["date"])
    for c in COLUMNS[2:]:
        df[c] = pd.to_numeric(df[c], errors="coerce").astype("float64")
    return df.sort_values(["date", "permno"]).drop_duplicates(["permno", "date"]).reset_index(drop=True)


def pull(
    start: str,
    end: str,
    source: str = "siz",
    out_dir: Path | None = None,
    tag: str | None = None,
    conn: Any | None = None,
) -> dict[str, int]:
    """Pull [start, end] month by month; write one Parquet per year (or one file if ``tag``)."""
    import wrds  # optional dependency: pip install -e .[wrds]

    out_dir = out_dir or raw_dir("crsp_daily")
    out_dir.mkdir(parents=True, exist_ok=True)
    db = conn or wrds.Connection()
    by_year: dict[int, list[pd.DataFrame]] = {}
    try:
        for s, e in month_chunks(start, end):
            t0 = time.time()
            # dates are generated by month_chunks (ISO strings), so inlining them is safe and
            # avoids depending on the bind-parameter style of the installed wrds/sqlalchemy.
            df = db.raw_sql(SQL[source].format(start=s, end=e), date_cols=["date"])
            df = _coerce(df)
            print(f"{s}..{e}: {len(df):,} rows in {time.time() - t0:.1f}s", flush=True)
            by_year.setdefault(pd.Timestamp(s).year, []).append(df)
    finally:
        if conn is None:
            db.close()

    counts = {}
    if tag:
        df = pd.concat([d for v in by_year.values() for d in v], ignore_index=True)
        df.to_parquet(out_dir / f"{tag}.parquet", index=False)
        counts[tag] = len(df)
    else:
        for year, parts in sorted(by_year.items()):
            df = pd.concat(parts, ignore_index=True)
            df.to_parquet(out_dir / f"{year}.parquet", index=False)
            counts[str(year)] = len(df)
    return counts


def describe(path: Path) -> None:
    """Print the schema and row count of a pulled file (used for the one-month check)."""
    df = pd.read_parquet(path)
    print(f"{path}: {len(df):,} rows, {df['permno'].nunique():,} permnos, "
          f"{df['date'].nunique()} dates [{df['date'].min().date()} .. {df['date'].max().date()}]")
    print(df.dtypes.to_string())
    print("null fraction:\n" + df.isna().mean().round(4).to_string())
    print(df.head().to_string())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--start", required=True)
    ap.add_argument("--end", required=True)
    ap.add_argument("--source", choices=sorted(SQL), default="siz")
    ap.add_argument("--tag", help="write a single file <tag>.parquet instead of per-year files")
    ap.add_argument("--dry-run", action="store_true", help="print SQL and chunks, do not connect")
    a = ap.parse_args()
    if a.dry_run:
        chunks = month_chunks(a.start, a.end)
        print(SQL[a.source].format(start=chunks[0][0], end=chunks[0][1]))
        print(f"{len(chunks)} monthly chunks: {chunks[0]} .. {chunks[-1]}")
        return
    counts = pull(a.start, a.end, a.source, tag=a.tag)
    print(counts)
    if a.tag:
        describe(raw_dir("crsp_daily") / f"{a.tag}.parquet")


if __name__ == "__main__":
    main()
